"""Pure logic for /api/teams/reply/status: where a Teams thread's reply stands.

The browser extension shows one button per Teams thread: copy the latest reply,
or regenerate it because the thread moved on. Everything that decides which one
lives here and touches neither the filesystem nor the network.

Why the body comes from a file
------------------------------
A session's final message is *usually* the reply body, but sessions routinely end
with a work report instead and keep the body in a file. Copying that report into
Teams would send a customer our notes, so the final message is never called
ready. The session saves the body to a file named in its prompt; only that file
makes a reply ``ready``. The final message remains a labelled fallback
(``unverified``), which the client must show before it copies.

Why staleness is decided against the base mid
---------------------------------------------
The base mid is the newest message stored when the run started. Anything newer,
or anything at or before it whose hash no longer matches, means the reply was
written without knowing it. Comparing client hash to client hash follows the sync
protocol: the server never recomputes one (see :mod:`.teams_sync`).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import datetime, timedelta

from .teams_sync import IncomingMessage, StoredMessage, ThreadRef

STATE_NONE = "none"
STATE_GENERATING = "generating"
STATE_READY = "ready"
STATE_UNVERIFIED = "unverified"
STATE_STALE = "stale"
STATE_POSTED = "posted"
STATE_FAILED = "failed"

SOURCE_FILE = "file"
SOURCE_FINAL_MESSAGE = "final_message"

#: Folder under the thread directory that holds one body file per run.
REPLY_DRAFT_DIR = "reply-drafts"

#: A run that left no trace of work after this long is reported as interrupted.
#: Shorter would call a session still queued for a slot a failure.
INTERRUPTED_AFTER = timedelta(minutes=30)

#: Share of 3-grams a Teams message must share with the draft to count as the
#: draft having been posted. People adjust a line before sending, so not exact.
POSTED_SIMILARITY = 0.8

MAX_EXCERPT_CHARS = 80

# The line the prompt asks for ahead of the reply; sessions sometimes put it in
# their final message, where it must not reach Teams.
_ANCHOR_LINE_RE = re.compile(r"\A\s*基準メッセージ[:：][^\n]*(?:\n\s*)*")


@dataclass(frozen=True)
class Draft:
    """A reply body and where it came from."""

    text: str
    source: str
    updated_at: str = ""


@dataclass(frozen=True)
class ThreadChange:
    """One way the thread differs from what the reply was based on."""

    mid: str
    kind: str  # "new" or "edited"
    author: str = ""
    excerpt: str = ""


@dataclass(frozen=True)
class ReplyStatus:
    """The verdict for one thread."""

    state: str
    changes: tuple[ThreadChange, ...] = ()
    draft: Draft | None = None
    reason: str = ""


def thread_key(ref: ThreadRef) -> str:
    """The identity a run is filed under.

    A conversation-scoped chat's root mid moves as older history arrives, so only
    its team identifies it — the same rule the vault uses to find its folder.
    """
    return ref.team if ref.conversation_scoped else ref.key


def draft_file_name(result_id: str) -> str:
    """The body file of one run. ``result_id`` is generated by the server."""
    return f"{result_id}.txt"


def render_draft_contract(path: str) -> str:
    """The prompt section telling a session where the reply body goes."""
    return (
        "## 返信本文の保存（必須）\n\n"
        "拡張機能の「最新の回答をコピー」は、"
        "次のファイルの中身をそのままクリップボードに入れます。\n\n"
        f"`{path}`\n\n"
        "- 改行チェックなどの確認がすべて済んだ完成版の返信本文を、"
        "UTF-8 のプレーンテキストで保存してください\n"
        "- Teams に貼る本文だけを入れてください。"
        "基準メッセージの行・作業メモ・確認事項の報告は入れません\n"
        "- 本文を修正したときは、後のターンでも必ずこのファイルを上書きしてください\n"
        "- このファイルがあなたの回答の正本です。無ければ「本文を確認できない」と画面に出ます"
    )


def strip_anchor_line(text: str) -> str:
    """Drop a leading anchor line from a final message used as a fallback."""
    return _ANCHOR_LINE_RE.sub("", text, count=1).strip()


def _squeeze(text: str) -> str:
    return re.sub(r"\s+", "", text or "")


def _trigrams(text: str) -> set[str]:
    return {text[i : i + 3] for i in range(len(text) - 2)}


def looks_like_draft(message_text: str, draft_text: str) -> bool:
    """Whether a Teams message is the draft, posted with at most light edits.

    Whitespace is dropped first because Teams re-renders line breaks. A linear
    3-gram comparison rather than an edit distance, since this runs on every
    status request while a popup is open.
    """
    a = _trigrams(_squeeze(message_text))
    b = _trigrams(_squeeze(draft_text))
    if not a or not b:
        return False
    return 2 * len(a & b) / (len(a) + len(b)) >= POSTED_SIMILARITY


def _excerpt(text: str) -> str:
    flat = " ".join((text or "").split())
    return flat if len(flat) <= MAX_EXCERPT_CHARS else flat[:MAX_EXCERPT_CHARS] + "…"


def _mid_value(mid: str) -> int:
    return int(mid) if mid.isdigit() else -1


def find_changes(
    *,
    base_mid: str | None,
    visible: list[IncomingMessage],
    stored: dict[str, StoredMessage],
    chain: dict[str, dict],
    draft_text: str,
) -> tuple[list[ThreadChange], bool]:
    """Compare the thread with the reply's base.

    Returns the changes, oldest first, and whether the draft itself showed up in
    the thread. Posted copies of the draft are not changes: the person's own
    answer must not make the answer look out of date.

    Without a base nothing can be called newer, so only edits are reported.
    """
    base = _mid_value(base_mid) if base_mid else None
    visible_by_mid = {msg.mid: msg for msg in visible}
    changes: list[ThreadChange] = []
    posted = False

    # Messages stored after the run started count even if not on screen: the
    # visible window is only what Teams has rendered right now.
    newer = (
        {mid for mid in (*visible_by_mid, *stored) if _mid_value(mid) > base}
        if base is not None
        else set()
    )
    for mid in sorted(newer, key=_mid_value):
        msg = visible_by_mid.get(mid)
        text = msg.text if msg else ""
        if draft_text and looks_like_draft(text, draft_text):
            posted = True
            continue
        author = (msg.author if msg else "") or str((chain.get(mid) or {}).get("author") or "")
        changes.append(ThreadChange(mid=mid, kind="new", author=author, excerpt=_excerpt(text)))

    # An unknown mid at or before the base is not an edit: the vault legitimately
    # stops at the point an early-stopped scan reached. Nor is a body Teams has not
    # rendered yet, whose empty text would hash differently from the stored one.
    edits = [
        msg
        for msg in visible
        if msg.mid not in newer
        and msg.text.strip()
        and msg.mid in stored
        and stored[msg.mid].hash != msg.hash
    ]
    for msg in sorted(edits, key=lambda m: _mid_value(m.mid)):
        changes.append(
            ThreadChange(mid=msg.mid, kind="edited", author=msg.author, excerpt=_excerpt(msg.text))
        )
    return changes, posted


def _is_interrupted(created_at: str, now: datetime) -> bool:
    try:
        created = datetime.fromisoformat(created_at)
    except (TypeError, ValueError):
        # An unreadable age must not leave the button stuck on "generating".
        return True
    return now - created > INTERRUPTED_AFTER


def choose_draft(*, file_draft: Draft | None, final_message: str | None) -> Draft | None:
    """Prefer the saved body; a final message is only ever a labelled fallback."""
    if file_draft is not None:
        return file_draft
    fallback = strip_anchor_line(final_message or "")
    return Draft(text=fallback, source=SOURCE_FINAL_MESSAGE) if fallback else None


def evaluate(
    *,
    run: dict | None,
    running: bool,
    file_draft: Draft | None,
    visible: list[IncomingMessage],
    stored: dict[str, StoredMessage],
    chain: dict[str, dict],
    now: datetime,
) -> ReplyStatus:
    """Decide the state of a thread's latest reply.

    ``run`` is the newest ingest row linked to the thread. The order matters: a
    turn in flight outranks everything because the file may be half-way through a
    revision, and a change in the thread outranks a finished draft because a
    stale draft must not look copyable.
    """
    if run is None:
        return ReplyStatus(state=STATE_NONE)
    if running:
        return ReplyStatus(state=STATE_GENERATING)

    status = run.get("status")
    draft = choose_draft(
        file_draft=file_draft,
        final_message=run.get("result") if status == "done" else None,
    )
    if draft is None:
        if status == "error":
            return ReplyStatus(state=STATE_FAILED, reason=str(run.get("error") or ""))
        if status == "running" and not _is_interrupted(str(run.get("created_at") or ""), now):
            return ReplyStatus(state=STATE_GENERATING)
        reason = (
            "セッションが返信本文を残さずに終わりました"
            if status == "done"
            else "セッションが途中で止まったようです"
        )
        return ReplyStatus(state=STATE_FAILED, reason=reason)

    changes, posted = find_changes(
        base_mid=run.get("teams_base_mid"),
        visible=visible,
        stored=stored,
        chain=chain,
        draft_text=draft.text,
    )
    if changes:
        return ReplyStatus(state=STATE_STALE, changes=tuple(changes), draft=draft)
    if posted:
        return ReplyStatus(state=STATE_POSTED, draft=draft)
    state = STATE_READY if draft.source == SOURCE_FILE else STATE_UNVERIFIED
    return ReplyStatus(state=state, draft=draft)
